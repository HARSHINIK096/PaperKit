const I18nContext = createContext();

export function I18nProvider({ children }) {
  const { user, updatePreferences } = useAuth();
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('paperkit_lang');
      if (saved && DICTIONARY[saved]) return saved;
      if (user?.preferences?.language && DICTIONARY[user.preferences.language]) return user.preferences.language;
    } catch {
      // storage exception safe
    }
    return 'en';
  });

  // Keep document language and localStorage in sync
  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem('paperkit_lang', lang);
    } catch {
      // ignore
    }
  }, [lang]);

  // Sync when user preference language updates externally
  useEffect(() => {
    const userPrefLang = user?.preferences?.language;
    if (userPrefLang && DICTIONARY[userPrefLang] && userPrefLang !== lang) {
      setLangState(userPrefLang);
    }
    // Only run when user?.preferences?.language changes, not on every lang state update
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [user?.preferences?.language]);

  const setLang = (newLang) => {
    if (DICTIONARY[newLang]) {
      setLangState(newLang);
      try {
        localStorage.setItem('paperkit_lang', newLang);
      } catch {
        // ignore
      }
      document.documentElement.lang = newLang;
      if (updatePreferences) {
        updatePreferences({ language: newLang });
      }
    }
  };

  const t = (key) => {
    return DICTIONARY[lang]?.[key] || DICTIONARY['en']?.[key] || key;
  };

  return (
    <I18nContext.Provider value={{ t, lang, setLang, supportedLanguages: SUPPORTED_LANGUAGES }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
